/**
 * Helper to match any route zone name to the real warehouse zone area
 */
export function matchZoneToWarehouseArea(zoneStr: string): WarehouseZoneArea | undefined {
  if (!zoneStr) return undefined;
  const clean = zoneStr.trim().toUpperCase().replace(/\s+/g, '');
  
  return REAL_WAREHOUSE_ZONES.find((area) => {
    const areaClean = area.code.toUpperCase();
    return clean.includes(areaClean) || areaClean.includes(clean);
  });
}
